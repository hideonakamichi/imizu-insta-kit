/* ============================================================
   「困りごと」タグ  —  制度カテゴリ (手当/助成/給付金/…) とは別軸の分類
   ------------------------------------------------------------
   ★なぜ必要か★
   category は「手当・助成・給付金・貸付・サービス・税制・年金」という
   行政側の分類。読者は「手当がほしい」ではなく「水道代が高い」「塾代が
   払えない」で探すので、この軸だけでは目的の制度にたどり着けない。
   /start はこのファイルの分類だけで組み立てる。

   ★1制度に複数タグを付けてよい★
   母子父子寡婦福祉資金貸付金のように、生活費にも住居にも進学にも使える
   制度があるため。逆に「なんとなく関係する」程度では付けない
   (どの見出しにも出てくるタグは、見出しとして機能しなくなる)。

   ★ひもづけのキーは program_code (id ではない)★
   id は DB の連番で、行の入れ替えや再登録でずれる。program_code は
   制度そのものを指すスラッグなので、こちらを正とする。
   ここに無い program_code の制度は、どの困りごとにも出ない (= 落ちても
   ページは壊れない)。新しい制度を登録したら CONCERN_MAP に足すこと。

   ★将来 DB に移すとき★
   supabase/concerns.sql に DDL とデータ移行 SQL を用意してある (未実行)。
   移したあとも「どの制度がどの困りごとか」の判断はこのファイルの内容が
   そのまま初期値になる。
   ============================================================ */

