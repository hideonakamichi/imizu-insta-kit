export const CONCERN_IDS = CONCERNS.map((c) => c.id);

/* ============================================================
   program_code → 困りごと id[] のひもづけ

   ★配布版はサンプル 3 件です★
   本番で使っていたひもづけ (数十件) は同梱していません。
   supabase/seed.sql のサンプル 3 件に対応する形だけ残してあります。

   ★ひもづけの原則 (ここは残す価値のあるルール)★
   - **推測で付けない。** 制度の対象経費・目的として一次情報に書かれているものだけ付ける
   - 1 つの対象に複数の困りごとを付けてよい
     (例: 用途が複数ある貸付なら、生活費・住まい・学費…と複数付く)
   - ここに無い program_code は concernsOf() が空配列を返すだけで、ページは壊れない

   ★別テーマで使う場合★
   「読者が自分の言葉で困りごとを選ぶ → 該当する対象が出る」という導線は、
   制度名を知らない読者の入口として有効です。CONCERNS の分類を
   自分のテーマの「読者の困りごと」に置き換えてください。
   ============================================================ */
export const CONCERN_MAP = {
  'sample-teate-a': ['money-now'],
  'sample-josei-b': ['medical'],
  'sample-kashitsuke-c': ['money-now', 'housing', 'highschool', 'work'],
};

export function concernsOf(programCode) {
  return CONCERN_MAP[programCode] ?? [];
}

/* 制度リスト (lib/supabase.js の getConcernSupports が返す形) を
   困りごと id ごとに束ねる。並べ方は呼び出し側に任せず、ここで決めきる:
     1. 解説記事があるものが先 (読者がすぐ読めるため)
     2. 全国の制度が先 (誰でも対象になりうるため)
     3. 同条件なら id 順 (DB 登録順 = だいたい重要な順)
   1件も無い困りごとは返さない (空の見出しを出さないため)。 */
export function groupByConcern(supports) {
  const buckets = new Map(CONCERN_IDS.map((id) => [id, []]));
  for (const s of supports) {
    for (const cid of concernsOf(s.program_code)) {
      buckets.get(cid)?.push(s);
    }
  }
  const rank = (s) => (s.has_article ? 0 : 1) * 10 + (s.prefectures?.length ? 1 : 0);
  return CONCERNS.map((c) => ({
    ...c,
    supports: (buckets.get(c.id) ?? []).sort((a, b) => rank(a) - rank(b) || a.id - b.id),
  })).filter((c) => c.supports.length > 0);
}
